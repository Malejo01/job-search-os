const ISO_SET: ReadonlySet<string> = new Set(ISO_COUNTRY_CODES);

/** `true` si es un código ISO-2 asignado, en mayúsculas. `XX` y cualquier otro no asignado, no. */
export function isIsoCountry(code: string | null | undefined): boolean {
  return typeof code === "string" && ISO_SET.has(code);
}

